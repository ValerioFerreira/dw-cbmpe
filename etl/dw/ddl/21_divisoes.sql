-- Previsto por unidade e divisao (soma dos quadros). `extra` = no de topo do quadro
-- que nenhuma divisao do app reivindicou (entra para a soma da unidade fechar).
CREATE TABLE IF NOT EXISTS core.qod_previsto_divisao (
    sigla     text    NOT NULL,
    ordem     integer NOT NULL,
    divisao   text    NOT NULL,
    previsto  integer NOT NULL,
    extra     boolean NOT NULL DEFAULT false,
    PRIMARY KEY (sigla, ordem)
);
ALTER TABLE core.qod_previsto_divisao OWNER TO etl_writer;

-- Divisao do organograma de cada funcao do catalogo (so as que casaram).
CREATE TABLE IF NOT EXISTS core.qod_funcao_divisao (
    id_funcao text PRIMARY KEY,
    divisao   text NOT NULL
);
ALTER TABLE core.qod_funcao_divisao OWNER TO etl_writer;

-- Quem esta lotado em cada divisao, por UNIDADE DO MILITAR (a do efetivo ativo).
CREATE TABLE IF NOT EXISTS core.qod_lotacao_divisao (
    sigla      text NOT NULL,
    divisao    text NOT NULL,
    matricula  text NOT NULL,       -- so digitos
    PRIMARY KEY (sigla, divisao, matricula)
);
ALTER TABLE core.qod_lotacao_divisao OWNER TO etl_writer;

-- Previsto por divisao: agregado, qualquer usuario logado le (GET /dados/metricas).
CREATE OR REPLACE VIEW marts.previsto_divisao AS
SELECT sigla, ordem, divisao AS nome, previsto, extra
FROM core.qod_previsto_divisao;

-- Lotacao por divisao: NOMINAL (matricula) -- so o backend, com recorte por perfil.
CREATE OR REPLACE VIEW marts.lotacao_divisao AS
SELECT l.sigla, l.divisao, e.matricula
FROM core.qod_lotacao_divisao l
JOIN marts.efetivo_nominal e ON e.matricula_normalizada = l.matricula AND e.sigla = l.sigla;

-- A divisao de cada funcao entra na lotacao por militar (mesma view, coluna nova no fim).
CREATE OR REPLACE VIEW marts.lotacao_militar AS
SELECT e.sigla,
       e.matricula,
       oc.id_funcao,
       oc.antiguidade,
       oc.bge,
       oc.cursos,
       oc.portaria,
       oc.funcao_de                          AS posto_funcao,
       f.tipo_funcao                         AS tipo,
       f.funcao,
       f.secao,
       f.ome_qod                             AS ome,
       f.ome_completa,
       f.localidade,
       d.divisao
FROM core.qod_ocupacao oc
JOIN marts.efetivo_nominal e ON e.matricula_normalizada = oc.matricula
LEFT JOIN core.qod_funcao f  ON f.id_funcao = oc.id_funcao
LEFT JOIN core.qod_funcao_divisao d ON d.id_funcao = oc.id_funcao;

GRANT SELECT ON marts.previsto_divisao TO app_reader, bi_reader;
GRANT SELECT ON marts.lotacao_divisao, marts.lotacao_militar TO app_reader;
REVOKE ALL ON marts.lotacao_divisao FROM bi_reader;
ALTER VIEW marts.previsto_divisao OWNER TO etl_writer;
ALTER VIEW marts.lotacao_divisao  OWNER TO etl_writer;
